export const NO_INCOME_TAX_STATES = STATES.filter(s => s.type === 'no_income_tax');

export const getStateBySlug = (slug) => {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();
  return STATES.find(s => s.slug === normalized || s.id.toLowerCase() === normalized) || null;
};

export const getStateById = (id) => {
  if (!id) return null;
  const upper = id.toUpperCase().trim();
  return STATES.find(s => s.id === upper) || null;
};
